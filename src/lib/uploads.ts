// Rules for the Blob demo's uploads. Uploads are open to anyone who signs in,
// so they're locked down: images only (checked from the file's bytes, not its
// name or the browser's claimed type), a size cap, and only the newest few kept.

export const UPLOAD_PREFIX = "uploads/";
// Server Actions accept 1 MB request bodies by default, multipart overhead
// included, so files stay comfortably below that.
export const MAX_UPLOAD_BYTES = 900 * 1024;
export const KEEP_UPLOADS = 12;

const signatures = [
  { type: "image/png", ext: "png", bytes: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a] },
  { type: "image/jpeg", ext: "jpg", bytes: [0xff, 0xd8, 0xff] },
  { type: "image/gif", ext: "gif", bytes: [0x47, 0x49, 0x46, 0x38] },
] as const;

export type ImageKind = { type: string; ext: string };

// Identifies PNG, JPEG, GIF and WebP from their magic bytes. SVG is refused
// on purpose: it's XML that can carry scripts.
export function sniffImage(bytes: Uint8Array): ImageKind | null {
  for (const s of signatures) {
    if (s.bytes.every((b, i) => bytes[i] === b)) return { type: s.type, ext: s.ext };
  }
  const ascii = (from: number, to: number) => String.fromCharCode(...bytes.subarray(from, to));
  if (bytes.length >= 12 && ascii(0, 4) === "RIFF" && ascii(8, 12) === "WEBP") return { type: "image/webp", ext: "webp" };
  return null;
}

export type UploadCheck = { ok: true; bytes: Uint8Array; kind: ImageKind } | { ok: false; error: string };

export async function checkUpload(file: FormDataEntryValue | null): Promise<UploadCheck> {
  if (!(file instanceof File) || file.size === 0) return { ok: false, error: "Choose an image first." };
  if (file.size > MAX_UPLOAD_BYTES) return { ok: false, error: `That file is ${Math.round(file.size / 1024)} KB; the limit is 900 KB.` };
  const bytes = new Uint8Array(await file.arrayBuffer());
  const kind = sniffImage(bytes);
  return kind ? { ok: true, bytes, kind } : { ok: false, error: "Only PNG, JPEG, GIF and WebP images are accepted." };
}

// Pathnames are generated by the server (a random id plus the sniffed
// extension), never taken from the visitor. The file route only serves names
// of exactly that shape, so it can't be pointed at anything else in the store.
export const uploadPathname = (ext: string) => `${UPLOAD_PREFIX}${crypto.randomUUID()}.${ext}`;
export const isUploadName = (name: string) => /^[0-9a-f-]{36}\.(png|jpg|gif|webp)$/.test(name);

export const blobConfigured = () => Boolean(process.env.BLOB_STORE_ID || process.env.BLOB_READ_WRITE_TOKEN);
